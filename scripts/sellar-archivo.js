/**
 * Sella El Archivo: lee misterio/archivo.local.json (no versionado) y
 * escribe src/components/jardin/datos.ts con poemas públicos, hashes,
 * las mesas 1–4 y 5–8, y los textos cifrados de las fases 2 y 3.
 * Seals The Archive: reads misterio/archivo.local.json (untracked) and
 * writes src/components/jardin/datos.ts with public poems, hashes,
 * tables 1–4 and 5–8, and the encrypted texts of phases 2 and 3.
 *
 * Uso / Usage: npm run archivo:sellar
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const FUENTE = path.join(ROOT, "misterio", "archivo.local.json");
const SALIDA = path.join(ROOT, "src", "components", "jardin", "datos.ts");

/** Normaliza una respuesta: minúsculas, sin tildes ni espacios. */
function normalizar(texto) {
  return String(texto)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/\s+/g, "");
}

/** Longitud-prefijo binario: concatena sin ambigüedad. */
function lp(textos) {
  const partes = [];
  for (const t of textos) {
    const b = Buffer.from(normalizar(t), "utf8");
    const len = Buffer.alloc(4);
    len.writeUInt32BE(b.length, 0);
    partes.push(len, b);
  }
  return Buffer.concat(partes);
}

/** Deriva una clave con HKDF. */
function derivar(ikm, salt, info) {
  return Buffer.from(crypto.hkdfSync("sha256", ikm, salt, Buffer.from(info, "utf8"), 32));
}

/** Cifra con AES-256-GCM. */
function cifrar(texto, clave) {
  const iv = crypto.randomBytes(12);
  const c = crypto.createCipheriv("aes-256-gcm", clave, iv);
  const cuerpo = Buffer.concat([c.update(texto, "utf8"), c.final(), c.getAuthTag()]);
  return { iv: iv.toString("base64"), data: cuerpo.toString("base64") };
}

/** Huella de un token para verificación individual. */
function huella(token) {
  return crypto.createHash("sha256").update(normalizar(token), "utf8").digest("base64");
}

/** Huella de una palabra de fase con la sal de época. */
function huellaFase(palabra, info, salt) {
  const hash = crypto.createHash("sha256");
  hash.update(salt);
  hash.update(Buffer.from(info, "utf8"));
  hash.update(Buffer.from(normalizar(palabra), "utf8"));
  return hash.digest("base64");
}

if (!fs.existsSync(FUENTE)) {
  console.error("Falta misterio/archivo.local.json (no versionado). / Missing untracked source.");
  process.exit(1);
}

const a = JSON.parse(fs.readFileSync(FUENTE, "utf8"));
const epoch = crypto.randomBytes(32);
const saltB64 = epoch.toString("base64");

const poemas = new Map(a.poemas.map((p) => [p.n, p]));
const mesa1 = [1, 2, 3, 4].map((n) => poemas.get(n).token);
const mesa2 = [5, 6, 7, 8].map((n) => poemas.get(n).token);

const k9 = derivar(lp(mesa1), epoch, "gc/p9/unlock/v1");
const k10 = derivar(lp(mesa2), epoch, "gc/p10/unlock/v1");

const m1 = cifrar(poemas.get(9).texto, k9);
const m2 = cifrar(poemas.get(10).texto, k10);

const palabra2 = a.fases.fase2.palabra;
const palabra3 = a.fases.fase3.palabra;
const palabraFinal = a.fases.final.palabra;

const kFase2 = derivar(Buffer.from(normalizar(palabra2), "utf8"), epoch, "gc/fase2/text/v1");
const kFase3 = derivar(Buffer.from(normalizar(palabra3), "utf8"), epoch, "gc/fase3/text/v1");

const f2 = cifrar(a.fases.fase2.texto, kFase2);
const f3 = cifrar(a.fases.fase3.texto, kFase3);

const h2 = huellaFase(palabra2, "gc/fase2/check/v1", epoch);
const h3 = huellaFase(palabra3, "gc/fase3/check/v1", epoch);
const hFinal = huellaFase(palabraFinal, "gc/final/check/v1", epoch);

const publicos = a.poemas
  .filter((p) => !p.cifrado)
  .map((p) => ({
    n: p.n,
    titulo: p.titulo,
    texto: p.texto,
  }));

const hashes = [1, 2, 3, 4, 5, 6, 7, 8].reduce((acc, n) => {
  acc[n] = huella(poemas.get(n).token);
  return acc;
}, {});

const datos = {
  version: 3,
  iteraciones: Number(a.iteraciones) || 200000,
  salt: saltB64,
  poemas: publicos,
  secciones: a.secciones,
  hashes,
  mesas: [
    { id: "mesa-1", poemas: [1, 2, 3, 4], iv: m1.iv, data: m1.data },
    { id: "mesa-2", poemas: [5, 6, 7, 8], iv: m2.iv, data: m2.data },
  ],
  fase2: { iv: f2.iv, data: f2.data },
  fase3: { iv: f3.iv, data: f3.data },
  hashFase2: h2,
  hashFase3: h3,
  hashFinal: hFinal,
  final: a.final,
};

const lineas = [
  "/**",
  " * GENERADO por scripts/sellar-archivo.js — no editar a mano.",
  " * WARNING: generated by scripts/sellar-archivo.js — do not edit by hand.",
  " * Poemas públicos, hashes, mesas cifradas y textos de fase cifrados.",
  " * Public poems, hashes, encrypted tables and encrypted phase texts.",
  " */",
  "",
  "export interface Poema {",
  "  n: number;",
  "  titulo: string;",
  "  texto: string;",
  "}",
  "",
  "export interface Seccion {",
  "  titulo: string;",
  "  texto: string;",
  "}",
  "",
  "export interface Mesa {",
  "  id: string;",
  "  poemas: number[];",
  "  iv: string;",
  "  data: string;",
  "}",
  "",
  "export interface Bloque {",
  "  iv: string;",
  "  data: string;",
  "}",
  "",
  `export const SALT = ${JSON.stringify(saltB64)};`,
  `export const ITERACIONES = ${datos.iteraciones};`,
  `export const POEMAS: readonly Poema[] = ${JSON.stringify(publicos)};`,
  `export const SECCIONES: Record<string, Seccion> = ${JSON.stringify(a.secciones)};`,
  `export const HASHES: Record<number, string> = ${JSON.stringify(hashes)};`,
  `export const MESAS: readonly Mesa[] = ${JSON.stringify(datos.mesas)};`,
  `export const FASE2: Bloque = ${JSON.stringify(datos.fase2)};`,
  `export const FASE3: Bloque = ${JSON.stringify(datos.fase3)};`,
  `export const HASH_FASE2 = ${JSON.stringify(h2)};`,
  `export const HASH_FASE3 = ${JSON.stringify(h3)};`,
  `export const HASH_FINAL = ${JSON.stringify(hFinal)};`,
  `export const FINAL = ${JSON.stringify(a.final)};`,
  "",
];

fs.mkdirSync(path.dirname(SALIDA), { recursive: true });
fs.writeFileSync(SALIDA, lineas.join("\n"), "utf8");
console.log(
  `datos.ts generado: ${publicos.length} poemas públicos, 2 mesas y 2 fases cifradas / generated`,
);
