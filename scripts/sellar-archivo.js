/**
 * Sella El Archivo: lee misterio/archivo.local.json (no versionado) y
 * escribe src/components/jardin/datos.ts con poemas públicos, hashes de
 * tokens y los poemas 9 y 10 cifrados. Las respuestas nunca se publican.
 * Seals The Archive: reads misterio/archivo.local.json (untracked) and
 * writes src/components/jardin/datos.ts with public poems, token hashes
 * and poems 9 and 10 encrypted. Answers are never published.
 *
 * Uso / Usage: npm run archivo:sellar
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const FUENTE = path.join(ROOT, "misterio", "archivo.local.json");
const SALIDA = path.join(ROOT, "src", "components", "jardin", "datos.ts");

/** Normaliza una respuesta: minúsculas, sin tildes ni espacios. */
function normalizar(texto) {
  return String(texto)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/\s+/g, "");
}

/** Longitud-prefijo binario: concatena sin ambigüedad. */
function lp(textos) {
  const partes = [];
  for (const t of textos) {
    const b = Buffer.from(normalizar(t), "utf8");
    const len = Buffer.alloc(4);
    len.writeUInt32BE(b.length, 0);
    partes.push(len, b);
  }
  return Buffer.concat(partes);
}

/** Deriva la clave de una mesa con HKDF. */
function derivarClave(tokens, salt, info) {
  return Buffer.from(crypto.hkdfSync("sha256", lp(tokens), salt, Buffer.from(info, "utf8"), 32));
}

/** Cifra con AES-256-GCM. */
function cifrar(texto, clave) {
  const iv = crypto.randomBytes(12);
  const c = crypto.createCipheriv("aes-256-gcm", clave, iv);
  const cuerpo = Buffer.concat([c.update(texto, "utf8"), c.final(), c.getAuthTag()]);
  return { iv: iv.toString("base64"), data: cuerpo.toString("base64") };
}

if (!fs.existsSync(FUENTE)) {
  console.error("Falta misterio/archivo.local.json (no versionado). / Missing untracked source.");
  process.exit(1);
}

const a = JSON.parse(fs.readFileSync(FUENTE, "utf8"));
const epoch = crypto.randomBytes(32);
const saltB64 = epoch.toString("base64");

const poemas = new Map(a.poemas.map((p) => [p.n, p]));
const mesa1 = [1, 2, 3, 4].map((n) => poemas.get(n).token);
const mesa2 = [5, 6, 7, 8].map((n) => poemas.get(n).token);

const k9 = derivarClave(mesa1, epoch, "gc/p9/unlock/v1");
const k10 = derivarClave(mesa2, epoch, "gc/p10/unlock/v1");

const m1 = cifrar(poemas.get(9).texto, k9);
const m2 = cifrar(poemas.get(10).texto, k10);

/** Hash de un token para verificación individual. */
function huella(token) {
  return crypto.createHash("sha256").update(normalizar(token), "utf8").digest("base64");
}

const publicos = a.poemas
  .filter((p) => !p.cifrado)
  .map((p) => ({
    n: p.n,
    titulo: p.titulo,
    texto: p.texto,
    ...(p.secreto ? { secreto: p.secreto } : {}),
  }));

const datos = {
  version: 1,
  iteraciones: Number(a.iteraciones) || 200000,
  salt: saltB64,
  poemas: publicos,
  secciones: a.secciones,
  hashes: [1, 2, 3, 4, 5, 6, 7, 8].reduce((acc, n) => {
    acc[n] = huella(poemas.get(n).token);
    return acc;
  }, {}),
  mesas: [
    { id: "mesa-1", poemas: [1, 2, 3, 4], iv: m1.iv, data: m1.data },
    { id: "mesa-2", poemas: [5, 6, 7, 8], iv: m2.iv, data: m2.data },
  ],
  final: a.final,
};

const lineas = [
  "/**",
  " * GENERADO por scripts/sellar-archivo.js — no editar a mano.",
  " * WARNING: generated by scripts/sellar-archivo.js — do not edit by hand.",
  " * Poemas públicos, hashes de token y poemas 9 y 10 cifrados.",
  " * Public poems, token hashes and poems 9 and 10 encrypted.",
  " */",
  "",
  "export interface Poema {",
  "  n: number;",
  "  titulo: string;",
  "  texto: string;",
  "  secreto?: string;",
  "}",
  "",
  "export interface Seccion {",
  "  titulo: string;",
  "  texto: string;",
  "}",
  "",
  "export interface Mesa {",
  "  id: string;",
  "  poemas: number[];",
  "  iv: string;",
  "  data: string;",
  "}",
  "",
  `export const SALT = ${JSON.stringify(saltB64)};`,
  `export const ITERACIONES = ${datos.iteraciones};`,
  `export const POEMAS: readonly Poema[] = ${JSON.stringify(publicos)};`,
  `export const SECCIONES: Record<string, Seccion> = ${JSON.stringify(a.secciones)};`,
  `export const HASHES: Record<number, string> = ${JSON.stringify(datos.hashes)};`,
  `export const MESAS: readonly Mesa[] = ${JSON.stringify(datos.mesas)};`,
  `export const FINAL = ${JSON.stringify(a.final)};`,
  "",
];

fs.mkdirSync(path.dirname(SALIDA), { recursive: true });
fs.writeFileSync(SALIDA, lineas.join("\n"), "utf8");
console.log(`datos.ts generado: ${publicos.length} poemas públicos, 2 mesas cifradas / generated`);
