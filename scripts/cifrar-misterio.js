/**
 * Cifra el misterio: lee misterio/secreto.local.json (no versionado) y
 * escribe src/components/misterio/datos.ts con SOLO sales, IVs y
 * criptotexto. Las pistas futuras quedan ilegibles sin la solución previa.
 * Encrypts the mystery: reads misterio/secreto.local.json (untracked) and
 * writes src/components/misterio/datos.ts with salts, IVs and ciphertext
 * only. Future clues are unreadable without the previous solution.
 *
 * Uso / Usage: npm run misterio:cifrar
 */
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SECRETO = path.join(ROOT, "misterio", "secreto.local.json");
const SALIDA = path.join(ROOT, "src", "components", "misterio", "datos.ts");

/**
 * Deriva la clave con PBKDF2-SHA256. / Derives the key with PBKDF2-SHA256.
 */
function claveDesde(texto, salt, iter) {
  return crypto.pbkdf2Sync(String(texto).trim().toLowerCase(), salt, iter, 32, "sha256");
}

/**
 * Cifra un objeto con AES-256-GCM. / Encrypts an object with AES-256-GCM.
 */
function cifrar(obj, texto, iter, saltFija) {
  const salt = saltFija ? Buffer.from(saltFija, "base64") : crypto.randomBytes(16);
  const iv = crypto.randomBytes(12);
  const key = claveDesde(texto, salt, iter);
  const c = crypto.createCipheriv("aes-256-gcm", key, iv);
  const cuerpo = Buffer.concat([c.update(JSON.stringify(obj), "utf8"), c.final(), c.getAuthTag()]);
  return {
    salt: salt.toString("base64"),
    iv: iv.toString("base64"),
    data: cuerpo.toString("base64"),
  };
}

if (!fs.existsSync(SECRETO)) {
  console.error("Falta misterio/secreto.local.json (no versionado). / Missing untracked secret file.");
  process.exit(1);
}

const s = JSON.parse(fs.readFileSync(SECRETO, "utf8"));
const iter = Number(s.iteraciones) || 200000;

/**
 * No publica las claves secretas de cada etapa. / Never publishes stage secrets.
 */
function publico(e) {
  return {
    id: e.id,
    tipo: e.tipo,
    ...(e.juego ? { juego: e.juego } : {}),
  };
}

const etapas = [];
let ultimaSolucion = null;
let ultimaSalt = null;
for (let i = 0; i < s.etapas.length; i++) {
  const e = s.etapas[i];
  const siguiente = s.etapas[i + 1];
  const carga = {
    pista: siguiente ? siguiente.pista : s.final.pista,
    fragmento: e.fragmento,
  };
  // Las etapas de código se cifran con SU solución y sal nueva; las de
  // sello reutilizan la sal de la última etapa estática para que la clave
  // guardada en el navegador sea la misma.
  // Code stages use THEIR solution and a fresh salt; seal stages reuse the
  // last static salt so the browser-stored key matches.
  const esCodigo = e.tipo === "codigo";
  const cifrado = esCodigo ? cifrar(carga, e.solucion, iter) : cifrar(carga, ultimaSolucion, iter, ultimaSalt);
  if (esCodigo) {
    ultimaSolucion = e.solucion;
    ultimaSalt = cifrado.salt;
  }
  etapas.push({
    ...publico(e),
    ...(i === 0 ? { claro: e.pista } : {}),
    ...cifrado,
  });
}

const finalCifrado = cifrar({ texto: s.final.texto }, s.final.solucion, iter);

const lineas = [
  "/**",
  " * GENERADO por scripts/cifrar-misterio.js — no editar a mano.",
  " * WARNING: generated by scripts/cifrar-misterio.js — do not edit by hand.",
  " * Solo contiene sales, IVs y criptotexto: sin la solución previa no",
  " * hay forma de leer pistas ni fragmentos futuros.",
  " * Only salts, IVs and ciphertext: without the previous solution there",
  " * is no way to read future clues or fragments.",
  " */",
  "",
  "export interface CargaCifrada {",
  "  salt: string;",
  "  iv: string;",
  "  data: string;",
  "}",
  "",
  "export interface EtapaCifrada {",
  '  id: string;',
  '  tipo: "codigo" | "sello";',
  '  juego?: "laberinto" | "tres";',
  "  salt?: string;",
  "  iv?: string;",
  "  data?: string;",
  "  claro?: string;",
  "}",
  "",
  `export const ITERACIONES = ${iter};`,
  "",
  "export const ETAPAS: readonly EtapaCifrada[] = [",
  ...etapas.map((e) => `  ${JSON.stringify(e)},`),
  "];",
  "",
  `export const FINAL: CargaCifrada = ${JSON.stringify(finalCifrado)};`,
  "",
];

fs.mkdirSync(path.dirname(SALIDA), { recursive: true });
fs.writeFileSync(SALIDA, lineas.join("\n"), "utf8");
console.log(`datos.ts generado: ${etapas.length} etapas + final / generated`);
